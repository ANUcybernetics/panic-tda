defmodule Mix.Tasks.Experiment.ExportImages do
  @shortdoc "Export an experiment's image outputs as AVIF files with embedded metadata"

  @moduledoc """
  Dumps every image-producing invocation as an AVIF file, organised into
  subfolders by network, prompt, and run. Each file gets EXIF/IPTC/XMP
  metadata describing the prompt, network, model, run/sequence, input text,
  and generation timestamp.

      $ mix experiment.export_images <experiment-id-prefix> [--output dir] [--limit N]

  Layout:

      <output>/<network>/<prompt-slug>/run_<n>/seq_<NNN>.avif

  Requires `exiftool` on the PATH.

  ## Options

    - `--output` — output directory (default: `./<short-id>_images`)
    - `--limit` — only export the first N images (useful for a quick test)
  """

  use Mix.Task

  require Ash.Query

  @impl Mix.Task
  def run(args) do
    {opts, rest, _} =
      OptionParser.parse(args, strict: [output: :string, limit: :integer])

    id_prefix =
      case rest do
        [id] ->
          id

        _ ->
          Mix.raise(
            "Usage: mix experiment.export_images <experiment-id-prefix> [--output dir] [--limit N]"
          )
      end

    System.find_executable("exiftool") || Mix.raise("exiftool not found on PATH")

    Mix.Task.run("app.start")

    experiment = find_experiment(id_prefix)

    output_dir = Keyword.get(opts, :output, "./#{short_id(experiment.id)}_images")
    File.mkdir_p!(output_dir)

    Mix.shell().info("Loading invocations from experiment #{short_id(experiment.id)}...")
    {invocations, text_lookup} = load_invocations(experiment.id)

    invocations =
      case Keyword.get(opts, :limit) do
        nil -> invocations
        n -> Enum.take(invocations, n)
      end

    total = length(invocations)
    Mix.shell().info("Exporting #{total} images to #{output_dir}/...")

    invocations
    |> Task.async_stream(
      fn inv -> write_invocation(inv, experiment, output_dir, text_lookup) end,
      max_concurrency: System.schedulers_online() * 2,
      timeout: 60_000,
      ordered: false
    )
    |> Stream.with_index(1)
    |> Stream.each(fn
      {{:ok, _}, idx} ->
        if rem(idx, 100) == 0, do: Mix.shell().info("  #{idx}/#{total}")

      {{:exit, reason}, idx} ->
        Mix.shell().error("  #{idx}/#{total} failed: #{inspect(reason)}")
    end)
    |> Stream.run()

    Mix.shell().info("Done. Images in #{output_dir}/")
  end

  defp find_experiment(id_prefix) do
    PanicTda.list_experiments!()
    |> Enum.find(&String.starts_with?(&1.id, id_prefix)) ||
      Mix.raise("No experiment found matching '#{id_prefix}'")
  end

  defp load_invocations(experiment_id) do
    text_lookup =
      PanicTda.Invocation
      |> Ash.Query.filter(run.experiment_id == ^experiment_id)
      |> Ash.Query.select([:id, :output_text])
      |> Ash.read!()
      |> Map.new(fn inv -> {inv.id, inv.output_text} end)

    image_invocations =
      PanicTda.Invocation
      |> Ash.Query.filter(run.experiment_id == ^experiment_id)
      |> Ash.Query.filter(not is_nil(output_image))
      |> Ash.Query.load([:run])
      |> Ash.Query.sort([:run_id, :sequence_number])
      |> Ash.read!()

    {image_invocations, text_lookup}
  end

  defp write_invocation(inv, experiment, output_dir, text_lookup) do
    run = inv.run

    network_slug = Enum.join(run.network, "_")
    prompt_slug = slugify(run.initial_prompt)
    run_dir = "run_#{run.run_number}"

    dir = Path.join([output_dir, network_slug, prompt_slug, run_dir])
    File.mkdir_p!(dir)

    seq = String.pad_leading(to_string(inv.sequence_number), 3, "0")
    path = Path.join(dir, "seq_#{seq}.avif")

    File.write!(path, inv.output_image)

    write_metadata(path, inv, run, experiment, text_lookup)
  end

  defp write_metadata(path, inv, run, experiment, text_lookup) do
    input_text =
      case inv.input_invocation_id && Map.get(text_lookup, inv.input_invocation_id) do
        text when is_binary(text) -> text
        _ -> run.initial_prompt
      end

    short_exp = short_id(experiment.id)
    network_str = Enum.join(run.network, " -> ")
    timestamp = format_timestamp(inv.started_at)

    headline =
      "#{run.initial_prompt} — #{network_str}, run #{run.run_number}, step #{inv.sequence_number}"

    caption =
      "Initial prompt: \"#{run.initial_prompt}\". Generated by #{inv.model} from input text: \"#{input_text}\". Run #{run.run_number}, step #{inv.sequence_number} of PANIC-TDA experiment #{short_exp}."

    user_comment =
      "Network: #{network_str} | Run: #{run.run_number} | Sequence: #{inv.sequence_number} | Model: #{inv.model} | Input: #{input_text}"

    keywords =
      ["panic-tda", slugify(run.initial_prompt) | run.network]
      |> Enum.join(", ")

    args =
      [
        "-overwrite_original",
        "-q",
        "-EXIF:ImageDescription=#{run.initial_prompt}",
        "-EXIF:Artist=#{inv.model}",
        "-EXIF:Software=PANIC-TDA experiment #{short_exp}",
        "-EXIF:UserComment=#{user_comment}",
        "-XMP-dc:Title=#{headline}",
        "-XMP-dc:Description=#{caption}",
        "-XMP-dc:Creator=#{inv.model}",
        "-XMP-dc:Source=PANIC-TDA experiment #{short_exp}",
        "-XMP-dc:Subject=#{keywords}"
      ]
      |> maybe_add_timestamp(timestamp)
      |> Kernel.++([path])

    case System.cmd("exiftool", args, stderr_to_stdout: true) do
      {_, 0} -> :ok
      {output, code} -> raise "exiftool failed (exit #{code}) for #{path}: #{output}"
    end
  end

  defp maybe_add_timestamp(args, ""), do: args

  defp maybe_add_timestamp(args, timestamp),
    do: args ++ ["-EXIF:DateTimeOriginal=#{timestamp}"]

  defp slugify(text) do
    text
    |> String.downcase()
    |> String.replace(~r/[^a-z0-9]+/, "_")
    |> String.trim("_")
  end

  defp format_timestamp(nil), do: ""

  defp format_timestamp(%DateTime{} = dt),
    do: Calendar.strftime(dt, "%Y:%m:%d %H:%M:%S")

  defp short_id(id), do: String.slice(id, 0, 8)
end
